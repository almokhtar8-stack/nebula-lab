"""Write test/TEST_REPORT.md from the machine-readable results of run_and_test.py.

    python scripts/write_test_report.py
"""
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
ENVS = ["colab-matched", "latest-pypi"]


def main():
    res = {e: json.loads((ROOT / "test" / f"results_{e}.json").read_text()) for e in ENVS}
    a, b = res["colab-matched"], res["latest-pypi"]
    names = [c["check"] for c in a["checks"]]
    assert names == [c["check"] for c in b["checks"]]
    n_pass = {e: sum(c["pass"] for c in res[e]["checks"]) for e in ENVS}
    env_rows = "\n".join(
        f"| {e} | {r['environment']['python']} | {r['environment']['numpy']} | {r['environment']['pandas']} | "
        f"{r['environment']['sklearn']} | {r['environment']['matplotlib']} | {n_pass[e]}/{len(names)} |"
        for e, r in res.items())
    rows = "\n".join(
        f"| {ca['check']} | {'pass' if ca['pass'] else '**FAIL**'} | {'pass' if cb['pass'] else '**FAIL**'} | "
        f"{ca['detail'].replace('|', '/')} |"
        for ca, cb in zip(a["checks"], b["checks"]))
    ind = a["independent"]
    t = a["timings"]
    qr = ROOT / "test" / "qr_verification.json"
    qr_text = ("Not run yet: the repository is not published." if not qr.exists() else
               "See `test/qr_verification.json`: " + ("every published file identical to the local copy."
                                                      if json.loads(qr.read_text()).get("all_identical")
                                                      else "**mismatch found; QR not made.**"))
    colab = ROOT / "test" / "COLAB_RUN.md"
    colab_text = colab.read_text() if colab.exists() else (
        "**Not yet done.** The notebook has not been run in Google Colab itself. Every result above comes from local "
        "kernels with older, Colab-era package versions and with the newest releases. Still to check once the "
        "repository is public: a timed cold start in Colab on a laptop, an iPad and a phone; Colab's rendering of "
        "the forms, the menu and dark mode; that a KAUST Google account may use Colab (otherwise students use a "
        "personal Gmail account). The steps are in COLAB_ACCEPTANCE_CHECK.md and HANDOVER.md.")
    report = f"""# NEBULA LAB test report

Generated by `scripts/write_test_report.py` from `test/results_*.json`, written by `scripts/run_and_test.py`.

## Where it was tested

Each run starts a new Jupyter kernel in a new, empty folder, the way a fresh Colab session starts.

| Environment | Python | NumPy | pandas | scikit-learn | Matplotlib | Checks passed |
|---|---|---|---|---|---|---|
{env_rows}

"colab-matched" uses the older versions a Colab runtime has shipped with; "latest-pypi" installs the newest releases (pandas 3 included). Together they bracket what a Colab session on the day is likely to run. Every text and table output was identical between the two environments.

## What was checked

| Check | colab-matched | latest-pypi | Detail (colab-matched) |
|---|---|---|---|
{rows}

## The numbers, recomputed independently

The test script recomputes the headline results straight from the CSV with NumPy and scikit-learn, without the lab's helper module, and compares them with what the notebook printed.

| Quantity (erythroid precursors held out) | Independent value |
|---|---|
| Training rows | {ind['n_train']:,} |
| Genes scored (open promoter) | {ind['n_test']:,} |
| Option A, promoter only: r / R² / median error / share of genes over-predicted | {ind['r_A']:.4f} / {ind['R2_A']:.4f} / {ind['fold_A']:.2f}-fold / {100 * ind['below_A']:.1f}% |
| Option B, promoter + 50 kb: r / R² / median error | {ind['r_B']:.4f} / {ind['R2_B']:.4f} / {ind['fold_B']:.2f}-fold |
| Copy-the-average control: r | {ind['r_control']:.4f} |
| Oracle (best training type, chosen using the answer) | {ind['oracle_type']}, r = {ind['r_oracle']:.4f} |

## Runtime (2 CPU cores, the size of a free Colab session)

* Five classroom steps: {sum(t['core_steps_s']):.1f} s of computing in total ({', '.join(f'{s:.1f}' for s in t['core_steps_s'])} s). Step ① includes reading and checking the 3.9 MB data file.
* Whole notebook including all ten optional exercises: {t['whole_notebook_s']:.1f} s wall time, kernel start included.
* Not included: Colab's own start-up (typically 10 to 30 s to connect a runtime) and the download from GitHub (about 4 MB).

## Failure paths tested

* Data missing and both download addresses blocked: a friendly card names the problem and links the project page; the cell stops with one short line instead of a traceback.
* Helper module missing and downloads blocked: a one-line message with the fallback link.
* Damaged data file on disk: the checksum rejects it, it is deleted, and a fresh download is attempted.
* Menu on option A: identical to step 3, and the notebook says so (deterministic).
* Step ④ skipped: step ⑤ computes what it needs itself.
* Rerun in a new kernel and folder: every output, including every figure's bytes, is identical.

## Visual review

Every figure was inspected at laptop and phone widths in a Jupyter rendering of the executed notebook. An independent review then recomputed every headline number (all matched), found no leakage, and raised 23 points on wording, metrics, timing, phone layout and visuals. Each point that could be fixed before publication was fixed and retested; the rest are listed under "Real Colab".

## Publication checks

{qr_text}

## Real Colab

{colab_text}
"""
    (ROOT / "test" / "TEST_REPORT.md").write_text(report)
    print("wrote test/TEST_REPORT.md")


if __name__ == "__main__":
    main()
